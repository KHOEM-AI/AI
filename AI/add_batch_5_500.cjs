function normalize(s) {
  return s.normalize("NFC").trim().toLowerCase().replace(/\s+/g, " ");
}

function escapeJs(s) {
  return s
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\r?\n/g, "\\n");
}

