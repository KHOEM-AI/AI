function normalize(s) {
  return s
    .normalize("NFC")
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ");
}

function escapeJs(s) {
  return String(s)
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\r?\n/g, "\\n");
}

// Existing first-field keys
const existing = new Set();

for (const line of text.split("\n")) {
  const m = line.match(/^\s*\["([^"]*)",/);
  if (m) existing.add(normalize(m[1]));
}

// Deduplicate new entries
const unique = [];
const batchSeen = new Set();

for (const [key, response] of entries) {
  const k = normalize(key);

  if (existing.has(k)) continue;
  if (batchSeen.has(k)) continue;

  batchSeen.add(k);
  unique.push([key, response]);
}

// Safety check
if (unique.length === 0) {
  console.log("⚠️ No new unique entries to add.");
  process.exit(0);
}

// Backup
const stamp = new Date().toISOString().replace(/[:.]/g, "-");
const backup = `${path}.bak-add500-${stamp}`;
fs.copyFileSync(path, backup);

// Insert before final array closing bracket
const pos = text.lastIndexOf("];");

if (pos === -1) {
  console.error("❌ Could not find final ];");
  process.exit(1);
}

const block =
  "\n\n  // ============================================================\n" +
  "  // Expansion Batch — 500\n" +
  "  // ============================================================\n" +
  unique
    .map(([key, response]) => `  ["${escapeJs(key)}", "${escapeJs(response)}"],`)
    .join("\n") +
  "\n";

const result = text.slice(0, pos) + block + text.slice(pos);

