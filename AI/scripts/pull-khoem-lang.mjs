import { pathToFileURL, fileURLToPath } from "node:url";
import { writeFileSync, readdirSync } from "node:fs";
import { homedir } from "node:os";
import { join, dirname } from "node:path";
const SRC = process.env.KHOEM_AI_DIR || join(homedir(), "KHOEM_AI_lang", "KHOEM_AI");
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "i18n", "khoemLang.generated.ts");
const LANGS = readdirSync(join(SRC, "dist", "src", "locales"), { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
function flatten(o, p = "", out = {}) {
  for (const [k, v] of Object.entries(o)) {
    const key = p ? p + "." + k : k;
    if (typeof v === "string") out[key] = v;
    else if (v && typeof v === "object") flatten(v, key, out);
  }
  return out;
}
const data = {};
for (const l of LANGS) {
  const m = await import(pathToFileURL(join(SRC, "dist", "src", "locales", l, "index.js")).href);
  data[l] = flatten(m.default);
}
writeFileSync(OUT, "// AUTO-GENERATED by scripts/pull-khoem-lang.mjs from KHOEM_AI - do not edit by hand\nexport const KHOEM_LANG: Record<string, Record<string, string>> = " + JSON.stringify(data, null, 2) + ";\n");
console.log("pulled", LANGS.join(","), Object.keys(data.en).length, "keys");
